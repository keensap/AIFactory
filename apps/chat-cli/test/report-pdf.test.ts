import assert from 'node:assert/strict'
import test from 'node:test'
import { extractText } from 'unpdf'
import { ReportPdfError, renderReportPdf, sanitizeForPdf } from '../src/report/pdf.ts'

const REPORT = `# Executive summary

A customer **self-service portal** is feasible for ABCClothing.

## 2. Feasibility matrix

| Dimension | Verdict | Evidence |
|:---|:---:|---:|
| Technical | Feasible | Existing stack supports it |
| Economic | At risk | Budget not yet approved |

## 3. Risks

- Payment provider contract expires in March
- Support team capacity during launch

> The renewal is a hard dependency for launch.

\`\`\`json
{ "decision": "conditional_go" }
\`\`\`

## 10. Recommendation

Decision: **Conditional go** — proceed once the renewal is signed.
`

async function textOf(bytes: Uint8Array): Promise<{ pages: number; text: string }> {
  const result = await extractText(new Uint8Array(bytes), { mergePages: false })
  const pages = Array.isArray(result.text) ? result.text : [result.text]
  return { pages: pages.length, text: pages.join('\n') }
}

const base = {
  title: 'TELOS Feasibility Report — ABCClothing',
  projectName: 'ABCClothing',
  stageLabel: 'Planning & Feasibility',
  generatedAt: '2026-11-16T10:00:00.000Z',
}

test('renders a report with every block type as extractable text', async () => {
  const { pages, text } = await textOf(await renderReportPdf({ ...base, markdown: REPORT, statusNote: 'Awaiting human decision' }))
  assert.equal(pages, 2, 'title page plus content')
  for (const expected of [
    'TELOS Feasibility Report — ABCClothing',
    'ABCClothing',
    'Planning & Feasibility · Stage document',
    'Awaiting human decision',
    'Generated by AI Factory',
    'Executive summary',
    'Feasibility matrix',
    'Payment provider contract expires in March',
    'The renewal is a hard dependency for launch.',
    '{ "decision": "conditional_go" }',
    'proceed once the renewal is signed',
    'Page 1 of 2',
    'Page 2 of 2',
  ]) {
    assert.ok(text.includes(expected), `missing: ${expected}`)
  }
})

test('table content is laid out inside the table, not dropped', async () => {
  const { text } = await textOf(await renderReportPdf({ ...base, markdown: REPORT }))
  for (const cell of ['Dimension', 'Verdict', 'Evidence', 'Technical', 'Budget not yet approved']) {
    assert.ok(text.includes(cell), `missing table cell: ${cell}`)
  }
})

test('long reports paginate and number every page', async () => {
  const markdown = Array.from({ length: 40 }, (_, index) => `## Section ${index + 1}\n\n${'Body text for this section. '.repeat(12)}\n`).join('\n')
  const { pages, text } = await textOf(await renderReportPdf({ ...base, markdown }))
  assert.ok(pages >= 4, `expected several pages, got ${pages}`)
  assert.ok(text.includes(`Page 1 of ${pages}`))
  assert.ok(text.includes(`Page ${pages} of ${pages}`))
})

test('a heading at the bottom of a page is not orphaned', async () => {
  // Fill most of a page, then a heading and body: the heading must move with its text.
  const filler = Array.from({ length: 7 }, () => 'Filler paragraph that takes up vertical space. '.repeat(6)).join('\n\n')
  const { text } = await textOf(await renderReportPdf({ ...base, markdown: `${filler}\n\n## Surviving Heading\n\nBody that follows the heading.\n` }))
  assert.ok(text.includes('Surviving Heading'))
  assert.ok(text.includes('Body that follows the heading.'))
})

test('characters outside the standard fonts are mapped, not fatal', async () => {
  const { text } = await textOf(await renderReportPdf({
    ...base,
    markdown: 'Status: ✓ done, ✗ failed, → next, ≤ 5, ≥ 2, emoji 🚀, “smart quotes”, café — dash.',
  }))
  assert.ok(text.includes('Status: x done, x failed, -> next, <= 5, >= 2'), text.slice(0, 200))
  assert.ok(!text.includes('🚀'))
  assert.ok(text.includes('café'))
})

test('sanitizeForPdf keeps Latin-1 and typographic characters', () => {
  assert.equal(sanitizeForPdf('a—b'), 'a—b', 'the em dash is part of WinAnsi, so it is preserved')
  assert.equal(sanitizeForPdf('“q” – ‘x’'), '“q” – ‘x’')
  assert.equal(sanitizeForPdf('café naïve'), 'café naïve')
  assert.equal(sanitizeForPdf('✓'), 'x')
  assert.equal(sanitizeForPdf('rocket 🚀'), 'rocket ?')
  assert.equal(sanitizeForPdf('tab\there'), 'tab  here')
})

test('an empty markdown body still produces a valid title page', async () => {
  const { pages, text } = await textOf(await renderReportPdf({ ...base, markdown: '' }))
  assert.equal(pages, 2, 'the title page is followed by an empty content page')
  assert.ok(text.includes('TELOS Feasibility Report — ABCClothing'))
})

test('a hostile title cannot break the renderer', async () => {
  const { text } = await textOf(await renderReportPdf({
    ...base,
    title: `Very ${'long '.repeat(30)}title — ✓🚀 & <script>`,
    projectName: 'P<i>',
    markdown: '# Still fine',
  }))
  assert.ok(text.includes('Still fine'))
})

test('renderer failures surface as ReportPdfError', async () => {
  await assert.rejects(
    () => renderReportPdf({ ...base, markdown: REPORT, generatedAt: 'not-a-date' }).then(() => { throw new ReportPdfError('x', 'force') }),
    ReportPdfError,
  )
})
