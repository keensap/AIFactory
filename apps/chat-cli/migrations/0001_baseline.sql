-- pgvector is required for `project_chunks.embedding`. Creating an extension
-- usually needs elevated rights, so report that clearly instead of failing with a
-- bare permission error: an administrator provisions it once per database.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'vector' AND n.nspname = 'public'
  ) THEN
    BEGIN
      CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
    EXCEPTION WHEN insufficient_privilege THEN
      RAISE EXCEPTION 'the pgvector extension is required: run CREATE EXTENSION vector as an administrator';
    END;
  END IF;
END $$;

